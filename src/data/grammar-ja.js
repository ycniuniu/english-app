const note = '等级只供学习参考，不是 JLPT 的官方语法表，也不能用来判断能不能合格。'

function point(fields) {
  return { origin: 'original-practice', license: LICENSE_ID, lang: 'ja', levelNote: note, examLinks: ['jlpt'], ...fields }
}

function ex(stem, options, answer, explanation) {
  const [a, b, c, d] = options
  return {
    stem,
    options: [
      { id: 'A', text: a },
      { id: 'B', text: b },
      { id: 'C', text: c },
      { id: 'D', text: d },
    ],
    answer,
    explanation,
  }
}

